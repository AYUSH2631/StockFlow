CREATE TABLE inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(100) NOT NULL,
    location_id VARCHAR(100) NOT NULL,
    quantity_on_hand INTEGER NOT NULL DEFAULT 0,
    quantity_reserved INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_inventory_items_sku_location UNIQUE (sku, location_id),
    CONSTRAINT ck_inventory_items_quantity_on_hand_nonnegative CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_inventory_items_quantity_reserved_valid
        CHECK (quantity_reserved >= 0 AND quantity_reserved <= quantity_on_hand)
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    reason VARCHAR(500),
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_reservations_order_id UNIQUE (order_id),
    CONSTRAINT ck_reservations_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'COMMITTED', 'RELEASED', 'EXPIRED'))
);

CREATE INDEX idx_reservations_status_expires_at ON reservations (status, expires_at);

CREATE TABLE reservation_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations (id) ON DELETE RESTRICT,
    inventory_item_id BIGINT NOT NULL REFERENCES inventory_items (id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_reservation_lines_reservation_inventory
        UNIQUE (reservation_id, inventory_item_id),
    CONSTRAINT ck_reservation_lines_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX idx_reservation_lines_inventory_item_id ON reservation_lines (inventory_item_id);

CREATE TABLE stock_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_item_id BIGINT NOT NULL REFERENCES inventory_items (id) ON DELETE RESTRICT,
    quantity_delta INTEGER NOT NULL,
    reason VARCHAR(500) NOT NULL,
    created_by VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_stock_adjustments_quantity_delta_nonzero CHECK (quantity_delta <> 0)
);

CREATE INDEX idx_stock_adjustments_inventory_created_at
    ON stock_adjustments (inventory_item_id, created_at DESC);
